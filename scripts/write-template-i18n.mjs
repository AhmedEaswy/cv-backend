function catalogKeys(kind, map, names = null, descs = null) {
    const out = {};
    for (const [slug, [name, desc]] of Object.entries(map)) {
        out[`templates.${kind}.${slug}.name`] = names?.[slug] || name;
        out[`templates.${kind}.${slug}.description`] = descs?.[slug] || desc;
    }
    return out;
}

