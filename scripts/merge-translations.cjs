const langDir = path.resolve(__dirname, '..', 'resources', 'lang');

let totalAdded = 0;
let totalUpdated = 0;
for (const locale of LOCALES) {
    const file = path.join(langDir, `${locale}.json`);
    const raw = fs.readFileSync(file, 'utf8');
    const json = JSON.parse(raw);
    let added = 0;
    let updated = 0;
    for (const [key, value] of Object.entries(NEW_KEYS)) {
        if (key in json) {
            // Overwrite — the new English values are the new design's source of truth.
            if (json[key] !== value) {
                json[key] = value;
                updated++;
            }
        } else {
            json[key] = value;
            added++;
        }
    }
    if (added > 0 || updated > 0) {
        fs.writeFileSync(file, JSON.stringify(json, null, 4) + '\n', 'utf8');
        console.log(`  + ${locale}: +${added} new, ~${updated} updated`);
        totalAdded += added;
        totalUpdated += updated;
    } else {
        console.log(`  = ${locale}: already up to date`);
    }
}

console.log(`\nDone. ${totalAdded} new keys, ${totalUpdated} updated across ${LOCALES.length} locales.`);
